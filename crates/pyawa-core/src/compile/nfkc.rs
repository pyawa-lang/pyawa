/// **标识符 NFKC 归一化**（PEP 3131 的逐字符近似）。
pub(super) fn normalize_identifier(name: &str) -> std::borrow::Cow<'_, str> {
    if name.is_ascii() {
        return std::borrow::Cow::Borrowed(name);
    }
    let mut normalized = String::with_capacity(name.len());
    let mut changed = false;
    for c in name.chars() {
        match NFKC_IDENTIFIER_TABLE.binary_search_by_key(&c, |(key, _)| *key) {
            Ok(index) => {
                normalized.push_str(NFKC_IDENTIFIER_TABLE[index].1);
                changed = true;
            }
            Err(_) => normalized.push(c),
        }
    }
    if changed {
        std::borrow::Cow::Owned(normalized)
    } else {
        std::borrow::Cow::Borrowed(name)
    }
}
