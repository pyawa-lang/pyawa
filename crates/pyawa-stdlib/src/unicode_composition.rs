/// 查规范组合对（`None` ＝ 不组合 ✓）。
pub fn compose_pair(a: u32, b: u32) -> Option<u32> {
    let mut low = 0usize;
    let mut high = COMPOSITION_PAIRS.len();
    while low < high {
        let middle = (low + high) / 2;
        let (first, second, composed) = COMPOSITION_PAIRS[middle];
        if (first, second) < (a, b) {
            low = middle + 1;
        } else if (first, second) > (a, b) {
            high = middle;
        } else {
            return Some(composed);
        }
    }
    None
}
